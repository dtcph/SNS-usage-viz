// Builds /data/country-map.json: ISO-3166 alpha-3 + numeric id, plus the name variants used by
// Data 1 (Statista) and Worldometer. Run once; edit EXTRA_NAMES below when a new name shows up in the
// browser console ("[country-map] unmapped ...").
// Usage: node build-country-map.mjs [out=../data/country-map.json]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const iso = require('i18n-iso-countries');
iso.registerLocale(require('i18n-iso-countries/langs/en.json'));

const out = path.resolve(process.argv[2] ?? '../data/country-map.json');

// Extra spellings keyed by alpha-3. "data1" = names used in the Statista files, "worldometer" = names on worldometers.info.
const EXTRA_NAMES = {
  USA: ['United States', 'United States of America'], GBR: ['United Kingdom'], RUS: ['Russia', 'Russian Federation'],
  KOR: ['South Korea', 'Korea, Republic of'], PRK: ['North Korea'], TWN: ['Taiwan'], HKG: ['Hong Kong'], MAC: ['Macao', 'Macau'],
  TUR: ['Turkey', 'Turkey (Türkiye)', 'Türkiye'], CZE: ['Czechia', 'Czech Republic', 'Czech Republic (Czechia)'],
  COD: ['DR Congo', 'Democratic Republic of the Congo'], COG: ['Republic of the Congo', 'Congo'],
  CIV: ['Ivory Coast', "Côte d'Ivoire"], PSE: ['State of Palestine', 'Palestine'], MMR: ['Myanmar', 'Burma'],
  TLS: ['Timor-Leste', 'East Timor'], SWZ: ['Eswatini', 'Swaziland'], MKD: ['North Macedonia', 'Macedonia'],
  VNM: ['Vietnam', 'Viet Nam'], IRN: ['Iran'], SYR: ['Syria'], LAO: ['Laos'], BOL: ['Bolivia'], VEN: ['Venezuela'],
  TZA: ['Tanzania'], MDA: ['Moldova'], BRN: ['Brunei'], CPV: ['Cape Verde', 'Cabo Verde'], FRO: ['Faeroe Islands', 'Faroe Islands'],
  VAT: ['Holy See', 'Vatican City'], FSM: ['Micronesia'], STP: ['Sao Tome & Principe', 'São Tomé and Príncipe'],
  KNA: ['Saint Kitts & Nevis'], VCT: ['Saint Vincent & the Grenadines'], VIR: ['U.S. Virgin Islands'], VGB: ['British Virgin Islands'],
  BLM: ['Saint Barthelemy'], SPM: ['Saint Pierre & Miquelon'], WLF: ['Wallis & Futuna'], TCA: ['Turks and Caicos'],
  CUW: ['Curaçao'], BES: ['Caribbean Netherlands'], GGY: ['Channel Islands'], FLK: ['Falkland Islands'],
};
// Numeric id of features in world-atlas that have no ISO entry are skipped (e.g. Kosovo has no id there).

const norm3 = (n) => String(n).padStart(3, '0');
const countries = [];
for (const [a2, a3] of Object.entries(iso.getAlpha2Codes()).map(([a2]) => [a2, iso.alpha2ToAlpha3(a2)])) {
  const name = iso.getName(a2, 'en');
  const alts = iso.getName(a2, 'en', { select: 'all' });
  const names = new Set([name, ...(Array.isArray(alts) ? alts : [alts]), ...(EXTRA_NAMES[a3] ?? [])].filter(Boolean));
  countries.push({ a3, a2, num: norm3(iso.alpha3ToNumeric(a3)), name, names: [...names] });
}
countries.sort((a, b) => a.a3.localeCompare(b.a3));
fs.writeFileSync(out, JSON.stringify({ note: 'ISO-3166 mapping; names[] holds all spellings (Statista data 1, Worldometer). Generated by tools/build-country-map.mjs', countries }, null, 1) + '\n');
console.log('wrote', out, countries.length, 'countries');
